import express from 'express';
import * as c from '../controllers/orderController.js';
import {authenticate,authorizeStaff,authorizeAdmin,allowRoles} from '../middlewares/authMiddleware.js';
const r=express.Router();r.use(authenticate);
r.route('/').post(c.createOrder).get(authorizeStaff,c.getAllOrders);
r.post('/quote',c.quoteOrder);r.get('/mine',c.getUserOrders);
r.get('/total-orders',authorizeAdmin,c.countTotalOrders);r.get('/total-sales',authorizeAdmin,c.calculateTotalSales);r.get('/total-sales-by-date',authorizeAdmin,c.calcualteTotalSalesByDate);
r.put('/:id/shops/:shopOrderId/deliver',allowRoles('shopkeeper'),c.markOrderAsDelivered);
r.get('/:id',c.findOrderById);
export default r;
